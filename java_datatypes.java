public class java_datatypes {
    public static void main(String[] args){
        //integer vs double
        int a = 2;
        double s = 0.5678;
        System.out.println(a);
        System.out.println(s);


        //character data type
        char g = 'A';
        System.out.println(g);
          /*char e = 'DCF'; (It give error because char store only one letter due
          to storage constraint)
        System.out.println(e);*/ //
        
    
        //Boolean type (true/false)
        boolean x = true;
        boolean y = false;
        System.out.println(x);
        System.out.println(y);


        //Long type (at the end of the number put "l")
        long b = 345L;
        System.out.println(b);


        //float vs double precision (at the end of the number put "f")
        float c = 0.43f;
        double d = 0.5678;
        System.out.println(c);
        System.out.println(d);


        //String
        String h = "Anuo Soni";
        System.out.println(h);

    }
    
}
